// Writes src/render/font.ts from assets/fonts/overpass-{400,700}-subset.ttf:
// each weight as base64, for the SVG's @font-face and for resvg, and its
// advance widths, so labels can be cut to length without a DOM. Run after
// changing the fonts:
//   node scripts/embed-font.ts
import { readFileSync, writeFileSync } from "node:fs";

const WEIGHTS = [400, 700] as const;

/** One font file's units per em and advance widths by code point. */
function metrics(ttf: Buffer): { unitsPerEm: number; widths: Record<number, number> } {
  const view = new DataView(ttf.buffer, ttf.byteOffset, ttf.byteLength);
  const tables = new Map<string, number>();
  for (let i = 0, n = view.getUint16(4); i < n; i++) {
    const at = 12 + i * 16;
    tables.set(ttf.toString("latin1", at, at + 4), view.getUint32(at + 8));
  }
  const table = (tag: string) => {
    const offset = tables.get(tag);
    if (offset === undefined) throw new Error(`No ${tag} table`);
    return offset;
  };

  const unitsPerEm = view.getUint16(table("head") + 18);
  const numberOfHMetrics = view.getUint16(table("hhea") + 34);
  const advance = (glyph: number) => view.getUint16(table("hmtx") + 4 * Math.min(glyph, numberOfHMetrics - 1));

  // cmap: the Unicode BMP subtable in format 4.
  const cmap = table("cmap");
  let format4 = -1;
  for (let i = 0, n = view.getUint16(cmap + 2); i < n; i++) {
    const [platform, encoding, offset] = [view.getUint16(cmap + 4 + i * 8), view.getUint16(cmap + 6 + i * 8), view.getUint32(cmap + 8 + i * 8)];
    if ((platform === 3 && encoding === 1) || platform === 0) {
      if (view.getUint16(cmap + offset) === 4) format4 = cmap + offset;
    }
  }
  if (format4 < 0) throw new Error("No format 4 cmap");
  const segments = view.getUint16(format4 + 6) / 2;
  const ends = format4 + 14;
  const starts = ends + segments * 2 + 2;
  const deltas = starts + segments * 2;
  const rangeOffsets = deltas + segments * 2;
  const widths: Record<number, number> = {};
  for (let s = 0; s < segments; s++) {
    const [start, end] = [view.getUint16(starts + s * 2), view.getUint16(ends + s * 2)];
    const [delta, rangeOffset] = [view.getInt16(deltas + s * 2), view.getUint16(rangeOffsets + s * 2)];
    for (let c = start; c <= end && c !== 0xffff; c++) {
      const raw = rangeOffset === 0 ? c : view.getUint16(rangeOffsets + s * 2 + rangeOffset + (c - start) * 2);
      const glyph = raw === 0 && rangeOffset !== 0 ? 0 : (raw + delta) & 0xffff;
      if (glyph !== 0) widths[c] = advance(glyph);
    }
  }
  return { unitsPerEm, widths };
}

const fonts = WEIGHTS.map((weight) => {
  const ttf = readFileSync(new URL(`../assets/fonts/overpass-${weight}-subset.ttf`, import.meta.url));
  return { weight, ttf, ...metrics(ttf) };
});
if (new Set(fonts.map((f) => f.unitsPerEm)).size !== 1) throw new Error("The weights disagree on units per em");

const out = `// Generated by scripts/embed-font.ts from assets/fonts/overpass-{400,700}-subset.ttf; do not edit.
// Overpass (SIL Open Font License 1.1, see assets/fonts/OFL.txt), the viewer's
// face, as static Regular and Bold instances subset to Latin-1 and a few symbols.

/** The family name the fonts are embedded and looked up under. */
export const FONT_FAMILY = "Overpass";

/** The weights embedded: Regular for running text, Bold for names, titles, codes and badges. */
export type FontWeight = ${WEIGHTS.join(" | ")};

/** Font units per em, the same for every weight. */
export const UNITS_PER_EM = ${fonts[0]!.unitsPerEm};

export interface EmbeddedFont {
  weight: FontWeight;
  /** The font file (TrueType), base64-encoded. */
  base64: string;
  /** Advance widths in font units, by code point. Characters missing here fall back to "M". */
  advances: Readonly<Record<number, number>>;
}

export const FONTS: readonly EmbeddedFont[] = [
${fonts.map((f) => `  { weight: ${f.weight}, base64: "${f.ttf.toString("base64")}", advances: ${JSON.stringify(f.widths)} },`).join("\n")}
];
`;
writeFileSync(new URL("../src/render/font.ts", import.meta.url), out);
for (const f of fonts) console.log(`Overpass ${f.weight}: ${Object.keys(f.widths).length} characters, ${f.ttf.length} bytes of font`);
